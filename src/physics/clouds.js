// 5.5: оптика объёмных кучевых облаков — эталон для шейдера gl/skyGL.js (константы подставляются в GLSL отсюда).
//
// • Ослабление в облаке (геометрическая оптика капель, r_e ≫ λ, Q_ext ≈ 2):
//     β = 3·LWC / (2·ρ_w·r_e)  ⇒  LWC = 0.5 г/м³, r_e = 10 мкм → β ≈ 75 км⁻¹ (Stephens 1978; Hess et al. 1998, OPAC).
//   Башня высотой 4 км — оптическая толщина в сотни: ядро непрозрачно, свет приходит многократным рассеянием.
// • Индикатриса капель — сильно вперёд (g ≈ 0.85). Берём смесь двух Хеньи — Гринстейна: вперёд g = 0.8 (70 %)
//   и слабо назад g = −0.3 (30 %) — так получаются и серебристый край у звезды, и светлая «изнанка» против звезды.
// • Многократное рассеяние — октавами (Wrenninge et al. 2013, «Oz: The Great and Volumetric»):
//     L = Σᵢ bⁱ · exp(−aⁱ·τ☉) · p(cⁱ·g),  a = b = c = 0.5, три октавы — свет «просачивается» глубже, чем по закону Бугера.
// • «Пудровый» эффект (Schneider & Vos 2015): край, обращённый от звезды, темнее — 1 − exp(−2τ) для малой глубины.
//
// Модельное упрощение: при шаге марша 1–3 км с настоящим β ≈ 75 км⁻¹ любой край облака непрозрачен, и облако
// получается вырезанным ножницами. Поэтому в марше используется эффективное β = 4 км⁻¹ на единицу «плотности»:
// плотность 0…1 — это доля облачного воздуха внутри шага (подсеточная облачность), а не водность капли.

export const CU = {
  base: 1.5,        // км — основание кучевых (уровень конденсации)
  height: 4.0,      // км — самые мощные башни: вершина до 5.5 км
  sigma: 4.0,       // км⁻¹ — эффективное ослабление на единицу плотности (см. выше)
  gF: 0.8, gB: -0.3, wF: 0.7,
  octA: 0.5, octB: 0.5, octC: 0.5, octaves: 3
};

/** Коэффициент ослабления облака, км⁻¹: LWC в г/м³, r_e в мкм */
export const cloudExtinction = (lwc, re) => 1500 * lwc / re;

/** Хеньи — Гринстейн, нормировка на 4π: ∫p dΩ = 4π */
export const hg = (g, c) => (1 - g * g) / Math.pow(1 + g * g - 2 * g * c, 1.5);

/** Индикатриса облака: смесь вперёд/назад */
export const cloudPhase = (c, k = 1) => CU.wF * hg(CU.gF * k, c) + (1 - CU.wF) * hg(CU.gB * k, c);

/** Свет звезды в точке облака: оптическая толщина до звезды τ☉, косинус угла рассеяния c — октавы многократного рассеяния */
export function cloudSunLight(tauSun, c) {
  let L = 0;
  for (let i = 0; i < CU.octaves; i++) {
    const a = Math.pow(CU.octA, i), b = Math.pow(CU.octB, i), k = Math.pow(CU.octC, i);
    L += b * Math.exp(-a * tauSun) * cloudPhase(c, k);
  }
  return L;
}

/** «Пудра»: тонкий слой у освещённой границы светится слабее, чем глубина облака */
export const powder = (tau) => 1 - Math.exp(-2 * tau);

/**
 * Марш сквозь однородный слой облака снизу вверх (наблюдатель под облаком, звезда над облаком):
 * толщина H км, плотность dens, высота звезды hs (рад), угол рассеяния cosG. Возвращает { L, T } —
 * относительную яркость основания облака и пропускание по лучу зрения. Эталон для проверок формы шейдера.
 */
export function slabFromBelow(H, dens, hs, cosG, N = 24) {
  const s = CU.sigma * dens, dz = H / N, mu = Math.max(0.05, Math.sin(hs));
  let T = 1, L = 0;
  for (let i = 0; i < N; i++) {
    const z = (i + 0.5) * dz;                         // высота над основанием
    const tauSun = s * (H - z) / mu;                  // до верхней границы по лучу к звезде
    const tauStep = s * dz;
    L += T * (1 - Math.exp(-tauStep)) * cloudSunLight(tauSun, cosG) * powder(s * Math.min(z + dz, 1.5));
    T *= Math.exp(-tauStep);
  }
  return { L, T };
}
