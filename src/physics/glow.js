// Тепловое свечение раскалённой поверхности (5.3) — насколько оно ярко по сравнению с отражённым светом звезды.
// Яркость поверхности в видимом свете: ∫B(λ, T)·V(λ)dλ (Планк × кривая чувствительности глаза).
// Отражённый свет звезды для белой (альбедо 1) поверхности: F/π, где F = π·B(T★)·(R★/d)² → ∫B(λ, T★)V(λ)dλ·(R★/d)².
// Отношение не зависит от констант: k = ∫B(T)V / [(R★/d)²·∫B(T★)V].
// Порог Дрейпера (798 K): начиная с него раскалённое тело видно глазом в темноте как тускло-красное. Венера (737 K)
// на ночной стороне глазом не светится; лава ~1400 K — светится ярко даже рядом с освещённой стороной.

const R_SUN_AU = 6.957e5 / 1.496e8;
const planck = (lnm, T) => { const l = lnm * 1e-9; return 1 / (Math.pow(l, 5) * (Math.exp(1.4388e-2 / (l * T)) - 1)); };
// кривая V(λ) дневного зрения — гауссова аппроксимация CIE 1924 (максимум 555 нм)
const V = (l) => 1.019 * Math.exp(-285.4 * Math.pow(l / 1000 - 0.559, 2));
const vis = (T) => { let s = 0; for (let l = 380; l <= 780; l += 5) s += planck(l, T) * V(l); return s * 5; };

/** Видимая яркость теплового излучения относительно отражённого света звезды (поверхность с альбедо 1) */
export function thermalGlowRatio(Tsurf, Tstar, rStarSun, dAU) {
  if (Tsurf < 500 || !(dAU > 0)) return 0;
  const geom = Math.pow(rStarSun * R_SUN_AU / dAU, 2);
  return vis(Tsurf) / Math.max(1e-300, geom * vis(Tstar));
}

/** Видимая яркость теплового излучения относительно тела при порогe Дрейпера (798 K) */
export function draperRatio(T) { return T < 500 ? 0 : vis(T) / vis(798); }
