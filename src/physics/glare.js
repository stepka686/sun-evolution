// Блик в глазу вместо «блума» (5.3). Ореол вокруг яркой звезды — не свечение воздуха, а рассеяние света в самом глазу
// (роговица, хрусталик, стекловидное тело). Его угловой профиль измерен: функция рассеяния точки CIE 2002 для
// «общего ослепляющего блика» (Vos & van den Berg, CIE 146:2002), возраст A лет, пигментация глаза p (0…1):
//   L_eq / E = 10/θ³ + (5/θ² + 0.1·p/θ)·(1 + (A/62.5)⁴) + 0.0025·p   [ср⁻¹, θ в градусах, 0.1° … 100°]
// Вблизи диска (θ < 0.1°) профиль насыщается — там его заменяет само изображение звезды.
// Доля блика по отношению к прямой яркости диска считается честно, а затем — тон-маппинг экрана.

export function cieGlarePSF(thetaDeg, age = 25, pigment = 0.5) {
  const t = Math.max(0.1, thetaDeg);
  const ageK = 1 + Math.pow(age / 62.5, 4);
  return 10 / (t * t * t) + (5 / (t * t) + 0.1 * pigment / t) * ageK + 0.0025 * pigment;
}

/**
 * Яркость блика относительно яркости диска звезды на угловом расстоянии θ.
 * Освещённость от диска E = L_disk · Ω (Ω = π·α², α — угловой радиус, рад) → L_glare / L_disk = PSF(θ) · Ω.
 */
export function glareRatio(thetaDeg, sunAngR, age = 25, pigment = 0.5) {
  const omega = Math.PI * sunAngR * sunAngR;
  return cieGlarePSF(thetaDeg, age, pigment) * omega;
}
